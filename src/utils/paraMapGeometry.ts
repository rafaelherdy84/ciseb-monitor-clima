export const PARA_MAP_WIDTH = 760;
export const PARA_MAP_HEIGHT = 560;
const PAD_X = 48;
const PAD_Y = 36;

// Geographic bounding box for Pará State
const MIN_LON = -59.2;
const MAX_LON = -45.8;
const MIN_LAT = -10.0;
const MAX_LAT = 2.7;

export function projectParaCoord(lat: number, lon: number): { x: number; y: number } {
  const x =
    PAD_X + ((lon - MIN_LON) / (MAX_LON - MIN_LON)) * (PARA_MAP_WIDTH - PAD_X * 2);
  const y =
    PAD_Y + ((MAX_LAT - lat) / (MAX_LAT - MIN_LAT)) * (PARA_MAP_HEIGHT - PAD_Y * 2);
  return { x, y };
}

export function coordsToSvgPath(coords: [number, number][], close = true): string {
  const pts = coords.map(([lat, lon]) => {
    const { x, y } = projectParaCoord(lat, lon);
    return `${x.toFixed(1)},${y.toFixed(1)}`;
  });
  return `M ${pts.join(' L ')}${close ? ' Z' : ''}`;
}

